import { expect, it } from "vitest";
import {
  TLS_KEY_LOG_MAX_BYTES,
  summarizeTlsKeyLog,
  tlsKeyLogReportSchema,
} from "./tlsKeyLog.js";

const hex = (seed: string, bytes: number): string =>
  seed.repeat(Math.ceil((bytes * 2) / seed.length)).slice(0, bytes * 2);
const randomA = hex("a1", 32);
const randomB = hex("b2", 32);
const randomC = hex("c3", 32);
const secrets = {
  master: hex("d4", 48),
  sha256: hex("e5", 32),
  sha384: hex("f6", 48),
  exporter: hex("07", 32),
  early: hex("18", 32),
};
const summarize = (text: string) => {
  const result = summarizeTlsKeyLog(Buffer.from(text, "latin1"), "fixture");
  if (!result.ok) throw result.error;
  return result.value;
};
const labels = (counts: Record<string, number>) => ({
  CLIENT_RANDOM: 0,
  CLIENT_EARLY_TRAFFIC_SECRET: 0,
  CLIENT_HANDSHAKE_TRAFFIC_SECRET: 0,
  SERVER_HANDSHAKE_TRAFFIC_SECRET: 0,
  CLIENT_TRAFFIC_SECRET_0: 0,
  SERVER_TRAFFIC_SECRET_0: 0,
  EARLY_EXPORTER_SECRET: 0,
  EXPORTER_SECRET: 0,
  ...counts,
});

it("counts TLS 1.2 and 1.3 labels, comments, blanks and distinct client randoms across CRLF and LF", () => {
  const text = [
    "# SSL/TLS secrets log file, generated by NSS",
    `CLIENT_RANDOM ${randomA} ${secrets.master}`,
    "",
    `CLIENT_HANDSHAKE_TRAFFIC_SECRET ${randomB} ${secrets.sha256}`,
    `SERVER_HANDSHAKE_TRAFFIC_SECRET ${randomB} ${secrets.sha256}\t `,
    `CLIENT_TRAFFIC_SECRET_0 ${randomB.toUpperCase()} ${secrets.sha384}`,
    `SERVER_TRAFFIC_SECRET_0 ${randomB} ${secrets.sha384}`,
    `EXPORTER_SECRET ${randomB} ${secrets.exporter}`,
    "   ",
    `CLIENT_EARLY_TRAFFIC_SECRET ${randomC} ${secrets.early}`,
    `EARLY_EXPORTER_SECRET ${randomC} ${hex("29", 64)}`,
  ].join("\r\n");
  expect(summarize(text)).toEqual({
    lines: { total: 11, comment_or_blank: 3, unrecognized: 0 },
    labels: labels({
      CLIENT_RANDOM: 1,
      CLIENT_HANDSHAKE_TRAFFIC_SECRET: 1,
      SERVER_HANDSHAKE_TRAFFIC_SECRET: 1,
      CLIENT_TRAFFIC_SECRET_0: 1,
      SERVER_TRAFFIC_SECRET_0: 1,
      EXPORTER_SECRET: 1,
      CLIENT_EARLY_TRAFFIC_SECRET: 1,
      EARLY_EXPORTER_SECRET: 1,
    }),
    client_randoms: { in_key_log: 3 },
    secret_values: "not-returned",
  });
  expect(summarize(`${text.replaceAll("\r\n", "\n")}\n`)).toEqual(
    summarize(text),
  );
});

it("counts each line once, including a final line without a terminator", () => {
  expect(summarize("")).toEqual({
    lines: { total: 0, comment_or_blank: 0, unrecognized: 0 },
    labels: labels({}),
    client_randoms: { in_key_log: 0 },
    secret_values: "not-returned",
  });
  expect(summarize("\n").lines).toEqual({
    total: 1,
    comment_or_blank: 1,
    unrecognized: 0,
  });
  const duplicate = `CLIENT_RANDOM ${randomA} ${secrets.master}`;
  expect(summarize(`${duplicate}\n${duplicate}`)).toMatchObject({
    lines: { total: 2, comment_or_blank: 0, unrecognized: 0 },
    labels: { CLIENT_RANDOM: 2 },
    client_randoms: { in_key_log: 1 },
  });
});

it("counts malformed, foreign and partial lines as unrecognized without echoing them", () => {
  const marker = "rea-unrecognized-line-marker";
  const malformed = [
    `RSA ${hex("aa", 8)} ${secrets.master}`,
    `PMS_CLIENT_RANDOM ${randomA} ${secrets.master}`,
    `client_random ${randomA} ${secrets.master}`,
    ` CLIENT_RANDOM ${randomA} ${secrets.master}`,
    `CLIENT_RANDOM  ${randomA} ${secrets.master}`,
    `CLIENT_RANDOM ${randomA.slice(2)} ${secrets.master}`,
    `CLIENT_RANDOM ${randomA} ${secrets.sha256}`,
    `CLIENT_RANDOM ${randomA}`,
    `CLIENT_RANDOM ${randomA} ${secrets.master} ${marker}`,
    `CLIENT_TRAFFIC_SECRET_0 ${randomA} ${secrets.sha256.slice(1)}`,
    `CLIENT_TRAFFIC_SECRET_0 ${randomA} ${secrets.sha256}0g`,
    `SERVER_TRAFFIC_SECRET_0 ${randomA} ${hex("ab", 40)}`,
    `${marker} ${randomA} ${secrets.sha256}`,
    `ï»¿CLIENT_RANDOM ${randomA} ${secrets.master}`,
    marker,
  ];
  const summary = summarize(malformed.join("\n"));
  expect(summary).toEqual({
    lines: {
      total: malformed.length,
      comment_or_blank: 0,
      unrecognized: malformed.length,
    },
    labels: labels({}),
    client_randoms: { in_key_log: 0 },
    secret_values: "not-returned",
  });
  expect(JSON.stringify(summary)).not.toContain(marker);
});

it("never returns secret, client random or line text in successful summaries", () => {
  const text = [
    `CLIENT_RANDOM ${randomA} ${secrets.master}`,
    `CLIENT_TRAFFIC_SECRET_0 ${randomB} ${secrets.sha256}`,
    `UNKNOWN_LABEL ${randomC} ${secrets.sha384}`,
  ].join("\n");
  const serialized = JSON.stringify(summarize(text)).toLowerCase();
  for (const value of [randomA, randomB, randomC, ...Object.values(secrets)])
    for (const fragment of [value, value.slice(0, 16), value.slice(-16)])
      expect(serialized).not.toContain(fragment.toLowerCase());
  expect(serialized).not.toContain("unknown_label");
});

it("refuses oversized input before scanning it, without quoting content", () => {
  const bytes = Buffer.alloc(TLS_KEY_LOG_MAX_BYTES + 1, 0x41);
  const secret = `CLIENT_RANDOM ${randomA} ${secrets.master}\n`;
  bytes.write(secret, 0, "latin1");
  const result = summarizeTlsKeyLog(bytes, "fixture");
  if (result.ok) throw new Error("Expected an oversized key log refusal");
  expect(result.error).toMatchObject({
    _tag: "AnalysisResourceConstraintError",
    operation: "fixture",
    resource: "file-size",
    reportedLimits: { tls_key_log_bytes: TLS_KEY_LOG_MAX_BYTES },
  });
  const serialized = JSON.stringify({
    message: result.error.message,
    reason: result.error.reason,
    limits: result.error.reportedLimits,
  });
  expect(serialized).not.toContain(randomA);
  expect(serialized).not.toContain(secrets.master);
  expect(serialized).not.toContain("AAAA");
  const boundary = summarizeTlsKeyLog(
    Buffer.alloc(TLS_KEY_LOG_MAX_BYTES, 0x23),
    "fixture",
  );
  if (!boundary.ok) throw boundary.error;
  expect(boundary.value.lines).toEqual({
    total: 1,
    comment_or_blank: 1,
    unrecognized: 0,
  });
});

it("binds reported counts to one key-log identity", () => {
  const summary = summarize(
    `# comment\nCLIENT_RANDOM ${randomA} ${secrets.master}\nnoise`,
  );
  const report = {
    path: "/captures/client.keys",
    sha256: "0".repeat(64),
    bytes: 200,
    ...summary,
  };
  expect(tlsKeyLogReportSchema.parse(report)).toEqual(report);
  for (const inconsistent of [
    { ...report, lines: { ...report.lines, total: 4 } },
    { ...report, labels: { ...report.labels, EXPORTER_SECRET: 1 } },
    { ...report, client_randoms: { in_key_log: 2 } },
    { ...report, secret_values: "returned" },
    { ...report, secret: secrets.master },
  ])
    expect(tlsKeyLogReportSchema.safeParse(inconsistent).success).toBe(false);
});
